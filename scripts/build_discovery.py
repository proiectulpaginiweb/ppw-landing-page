#!/usr/bin/env python3
"""Generate discovery files from the same HTML visitors read (standard library only)."""
from hashlib import sha256
from html import escape
from html.parser import HTMLParser
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
SITE = 'https://www.proiectulpaginiweb.ro/'
NAME = 'Proiectul Pagini Web'

class Node:
    def __init__(self, tag='', attrs=()):
        self.tag, self.attrs, self.children = tag, dict(attrs), []
    def text(self):
        return re.sub(r'\s+', ' ', ' '.join(c.text() if isinstance(c, Node) else c for c in self.children)).strip()
    def all(self, predicate):
        for c in self.children:
            if isinstance(c, Node):
                if predicate(c):
                    yield c
                yield from c.all(predicate)
    def first(self, predicate):
        return next(self.all(predicate))

class Document(HTMLParser):
    VOID = {'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]
        self.feed(source)
    def handle_starttag(self, tag, attrs):
        if tag == 'br':
            self.stack[-1].children.append(' ')
            return
        n = Node(tag, attrs)
        self.stack[-1].children.append(n)
        if tag not in self.VOID:
            self.stack.append(n)
    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in self.VOID:
            self.handle_endtag(tag)
    def handle_endtag(self, tag):
        for i in range(len(self.stack)-1, 0, -1):
            if self.stack[i].tag == tag:
                self.stack = self.stack[:i]
                return
    def handle_data(self, text):
        self.stack[-1].children.append(text)

html_path = ROOT / 'index.html'
source = html_path.read_text()
doc = Document(source).root
main = doc.first(lambda n: n.tag == 'main')
description = doc.first(lambda n: n.tag == 'meta' and n.attrs.get('name') == 'description').attrs['content']
title = doc.first(lambda n: n.tag == 'title').text()
services = list(main.all(lambda n: n.tag == 'article' and 'service' in n.attrs.get('class','').split()))
service_nodes = []
for i, service in enumerate(services, 1):
    service_nodes.append({
        '@type': 'Service', '@id': SITE + '#serviciu-' + str(i),
        'name': service.first(lambda n: n.tag == 'h3').text(),
        'description': service.first(lambda n: n.tag == 'p').text(),
        'url': SITE + '#posibilitati', 'provider': {'@id': SITE + '#organizatie'},
    })
graph = [
    {'@type':'Organization', '@id':SITE+'#organizatie', 'name':NAME, 'url':SITE,
     'description':description, 'logo':SITE+'assets/ppw.png',
     'contactPoint':{'@type':'ContactPoint','contactType':'Informații despre servicii','url':SITE+'#contact','availableLanguage':['ro']},
     'hasOfferCatalog':{'@type':'OfferCatalog','name':'Servicii IA','itemListElement':[
         {'@type':'Offer','itemOffered':{'@id':s['@id']}} for s in service_nodes]}},
    {'@type':'WebSite','@id':SITE+'#site','url':SITE,'name':NAME,'inLanguage':'ro','publisher':{'@id':SITE+'#organizatie'}},
    {'@type':'WebPage','@id':SITE+'#pagina','url':SITE,'name':title,'description':description,'inLanguage':'ro',
     'isPartOf':{'@id':SITE+'#site'},'about':{'@id':SITE+'#organizatie'}},
    *service_nodes,
]
block = '\n'.join([
    '<!-- discovery:start; generated by scripts/build_discovery.py -->',
    f'<link rel="canonical" href="{SITE}" />',
    '<meta name="robots" content="index, follow, max-image-preview:large" />',
    '<meta property="og:type" content="website" />',
    '<meta property="og:locale" content="ro_RO" />',
    f'<meta property="og:site_name" content="{NAME}" />',
    f'<meta property="og:url" content="{SITE}" />',
    f'<meta property="og:image" content="{SITE}assets/ppw.png" />',
    f'<meta property="og:image:alt" content="Sigla {NAME}" />',
    f'<link rel="alternate" type="text/markdown" href="{SITE}index.md" title="Conținut în format Markdown" />',
    f'<link rel="describedby" href="{SITE}llms.txt" type="text/plain" />',
    f'<link rel="sitemap" type="application/xml" href="{SITE}sitemap.xml" />',
    '<script type="application/ld+json">'+json.dumps({'@context':'https://schema.org','@graph':graph},ensure_ascii=False,indent=2)+'</script>',
    '<!-- discovery:end -->'
])
if '<!-- discovery:start;' in source:
    source = re.sub(r'<!-- discovery:start;.*?<!-- discovery:end -->',lambda m:block,source,flags=re.S)
else:
    source = source.replace('</head>',block+'\n</head>')
for asset in ('script.js','styles.css'):
    version=sha256((ROOT/asset).read_bytes()).hexdigest()[:12]
    source=re.sub(r'((?:src|href)="'+re.escape(asset)+r')(?:\?[^\"]*)?"',lambda m:m[1]+'?v='+version+'"',source)
html_path.write_text(source)

# Content is taken from visible headings, prose, lists and every journey panel.
lines = ['# '+NAME, '', '> '+description, '', 'Site oficial: '+SITE, '', 'Limba: română.', '']
IGNORE = {'script','style','svg','form','button'}
def markdown(node):
    if node.tag in IGNORE or node.attrs.get('aria-hidden') == 'true':
        return
    if node.tag == 'li' and any(True for _ in node.all(lambda n: 'step-icon' in n.attrs.get('class', '').split())):
        number = node.first(lambda n: 'step-icon' in n.attrs.get('class', '').split()).text()
        title = node.first(lambda n: n.tag == 'strong').text()
        description = node.first(lambda n: n.tag == 'span' and 'step-icon' not in n.attrs.get('class', '').split()).text()
        lines.extend([f'{int(number)}. **{title}** — {description}', ''])
        return
    if node.tag in {'h1','h2','h3','p','li','summary'}:
        text = node.text().replace('＋','').replace('✳','').strip()
        if text:
            prefix = '#' * int(node.tag[1]) + ' ' if node.tag in {'h1','h2','h3'} else '- ' if node.tag == 'li' else '### ' if node.tag == 'summary' else ''
            lines.extend([prefix+text,''])
        return
    if 'journey-deliverable' in node.attrs.get('class','').split():
        lines.extend(['**Ce obții:** '+node.first(lambda n:n.tag=='strong').text(),''])
        return
    for child in node.children:
        if isinstance(child, Node): markdown(child)
markdown(main)
lines.extend(['## Contact','','Folosește formularul de pe '+SITE+'#contact pentru a trimite numele, adresa de e-mail, interesul și descrierea proiectului.',''])
(ROOT/'index.md').write_text('\n'.join(lines))

# Keep a readable article copy in sync with the visible HTML.
article_path = ROOT/'blog/internetul-agentic-este-aici/index.html'
article = Document(article_path.read_text()).root
article_main = article.first(lambda n: n.tag == 'article' and 'post' in n.attrs.get('class', '').split())
article_body = article_main.first(lambda n: 'post-body' in n.attrs.get('class', '').split())
article_title = article_main.first(lambda n: n.tag == 'h1').text()
article_lead = article_main.first(lambda n: 'post-lead' in n.attrs.get('class', '').split()).text()
article_date = article_main.first(lambda n: n.tag == 'time').attrs['datetime']

def inline_markdown(node):
    if isinstance(node, str):
        return node
    content = ''.join(inline_markdown(c) for c in node.children)
    if node.tag == 'a':
        return '[' + content.strip() + '](' + node.attrs['href'] + ')'
    return content

article_lines = [
    '# ' + article_title, '',
    'Publicat: ' + article_date, '',
    'Articol: ' + SITE + 'blog/internetul-agentic-este-aici/', '',
    article_lead, '',
]
for child in article_body.children:
    if not isinstance(child, Node):
        continue
    if child.tag == 'h2':
        article_lines.extend(['## ' + child.text(), ''])
    elif child.tag == 'p':
        article_lines.extend([re.sub(r'\s+', ' ', inline_markdown(child)).strip(), ''])
    elif child.tag == 'blockquote':
        article_lines.extend(['> ' + child.text(), ''])
    elif 'post-facts' in child.attrs.get('class', '').split():
        for fact in child.all(lambda n: n.tag == 'div'):
            article_lines.extend(['### ' + fact.first(lambda n: n.tag == 'strong').text(), ''])
            paragraph = fact.first(lambda n: n.tag == 'p')
            article_lines.extend([re.sub(r'\s+', ' ', inline_markdown(paragraph)).strip(), ''])
article_markdown = '\n'.join(article_lines).rstrip() + '\n'
(ROOT/'blog/internetul-agentic-este-aici/index.md').write_text(article_markdown)

(ROOT/'llms.txt').write_text(f'''# {NAME}

> {description}

Site oficial în limba română: {SITE}

## Conținut

- [Prezentare completă în Markdown]({SITE}index.md): serviciile, cele patru etape ale colaborării, principiile și întrebările frecvente.
- [Conținut integral]({SITE}llms-full.txt): textul paginii principale și al articolului.
- [Pagina principală]({SITE}): versiunea HTML în română.
- [Blog]({SITE}blog/): articole despre tehnologie și experiențe digitale.
- [Internetul agentic este aici]({SITE}blog/internetul-agentic-este-aici/): articol despre date clare, modele LLM, instrumente și controlul acțiunilor agenților IA.
- [Articolul în Markdown]({SITE}blog/internetul-agentic-este-aici/index.md): copia textuală completă, cu trimiteri către sursele citate.
- [Servicii]({SITE}#posibilitati): agenți IA, automatizarea proceselor și experiențe digitale cu IA.
- [Parcursul colaborării]({SITE}#parcurs): descoperire, proiectare, construcție și îmbunătățire.
- [Întrebări frecvente]({SITE}#intrebari): explicații despre agenți IA, proiecte-pilot și date.
- [Contact]({SITE}#contact): formularul de contact.

Exemplul de proces pentru relația cu clienții este ilustrativ. Pagina nu publică prețuri, garanții de performanță sau mărturii ale clienților.
''')
# Full content is regenerated from the visible pages.
(ROOT/'llms-full.txt').write_text((ROOT/'index.md').read_text().rstrip() + '\n\n---\n\n' + article_markdown)
(ROOT/'.nojekyll').touch()
(ROOT/'robots.txt').write_text('User-agent: *\nAllow: /\n\nSitemap: '+SITE+'sitemap.xml\n')
(ROOT/'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>'+escape(SITE)+'</loc></url>\n  <url><loc>'+escape(SITE+'blog/')+'</loc></url>\n  <url><loc>'+escape(SITE+'blog/internetul-agentic-este-aici/')+'</loc></url>\n</urlset>\n')
print('Au fost generate metadatele canonice, JSON-LD, robots.txt, sitemap.xml, llms.txt și index.md din pagina HTML în română.')
